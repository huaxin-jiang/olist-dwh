-- ============================================================
-- Olist 项目专用账号与连接
-- 脚本 00：创建项目专用数据库用户
-- ============================================================
-- 【用途】
--   为本项目创建独立账号，只对 olist_db 有权限，
--   使其在 Navicat 中新建连接后只能看到 olist_db，
--   避免与课程作业的其他数据库混在一起。
--
-- 【为什么要这么做 —— 实现要点：最小权限原则】
--   生产环境绝不用 root 连接应用，原因有三：
--     1. root 权限过大，一旦被注入或泄露，整个实例失守
--     2. 误操作（如 DROP DATABASE）无法挽回
--     3. 无法审计"谁改了什么"（多人共用一个账号，责任不清）
--   正确做法：按业务/项目分配账号，只授予必要权限。
--
-- 【执行方式】
--   必须以 root 身份执行（在 Navicat 的 root 连接里跑）
-- ============================================================

-- ------------------------------------------------------------
-- 第一步：创建项目专用用户
-- ------------------------------------------------------------
-- 用户名：olist_dev（仅限本地连接 localhost）
-- 密码：   <YOUR_PASSWORD>    ← 请改成你自己的密码，改完记住
--
-- 说明：
--   'localhost' 表示只允许本机连接；
--   若写成 '%' 则允许任意主机连接（仅限局域网开发场景，生产禁用）
--
--   IDENTIFIED WITH mysql_native_password：
--   MySQL 8 默认用 caching_sha2_password，部分旧版 Navicat 不支持，
--   显式指定 native_password 可避免"Client does not support
--   authentication protocol"报错。
--   你的 my.ini 里 authentication_policy 已设为 mysql_native_password，
--   这一步是双保险。
-- ------------------------------------------------------------
DROP USER IF EXISTS 'olist_dev'@'localhost';

CREATE USER 'olist_dev'@'localhost'
    IDENTIFIED WITH mysql_native_password BY '<YOUR_PASSWORD>';

-- ------------------------------------------------------------
-- 第二步：只授予 olist_db 的权限
-- ------------------------------------------------------------
-- 注意：这里给的是 olist_db.* 的全部权限（建表、导入、查询、改数据），
--       因为你要在这个库里做完整开发。
--       如果是只读的分析账号，应改为只 GRANT SELECT。
-- ------------------------------------------------------------
GRANT ALL PRIVILEGES ON olist_db.* TO 'olist_dev'@'localhost';

-- ------------------------------------------------------------
-- 第三步：刷新权限（让授权立即生效）
-- ------------------------------------------------------------
-- 说明：修改 mysql.user 表后必须 FLUSH PRIVILEGES，
--       否则权限不会立即加载到内存。
--       用 CREATE USER / GRANT 语句通常会自动刷新，
--       但显式执行一次更稳妥（也是实现说明的细节）。
-- ------------------------------------------------------------
FLUSH PRIVILEGES;

-- ------------------------------------------------------------
-- 第四步：验证
-- ------------------------------------------------------------
-- 4.1 查看该用户的权限（应只看到 olist_db 相关）
SHOW GRANTS FOR 'olist_dev'@'localhost';

-- 4.2 查看所有用户（确认创建成功）
SELECT
    user       AS 用户名,
    host       AS 允许来源,
    plugin     AS 认证插件
FROM mysql.user
WHERE user = 'olist_dev';

-- 4.3 验证隔离效果：模拟该用户能看到哪些库
--     （执行结果应只有 information_schema 和 olist_db）
SHOW DATABASES;
